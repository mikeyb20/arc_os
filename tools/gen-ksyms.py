#!/usr/bin/env python3
"""Kernel symbol table for panic backtraces (M1-04).

The kernel links twice. The first link (kernel_stage1.elf) carries an empty
table; this script reads its function symbols and writes ksyms.c, which the
second link adds in its own section after .rodata (linker.ld), so no function
moves. --check confirms that: both links must have identical function
addresses, or the build fails.

    gen-ksyms.py --nm NM --out ksyms.c kernel_stage1.elf
    gen-ksyms.py --nm NM --empty --out ksyms_empty.c
    gen-ksyms.py --nm NM --check kernel_stage1.elf kernel.elf

Table (lib/ksyms.h): sorted 32-bit offsets from KSYM_BASE, 32-bit offsets
into one NUL-separated name blob, and ksym_end, the offset of _text_end
(linker.ld): addresses at or past it are not kernel code.
"""

import argparse
import subprocess
import sys

KSYM_BASE = 0xFFFFFFFF80000000   # KERNEL_VMA in linker.ld


def text_symbols(nm, elf):
    out = subprocess.run([nm, "-n", "--defined-only", elf], check=True, capture_output=True,
                         text=True).stdout
    syms = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3 or parts[1] not in ("T", "t") or "." in parts[2]:
            continue   # functions only; NASM local labels (_start.halt) name their function
        addr = int(parts[0], 16)
        if addr < KSYM_BASE or addr - KSYM_BASE >= 1 << 32:
            continue
        syms.append((addr, parts[2]))
    return syms


def write_table(out, syms):
    seen, names, offsets, name_offs = set(), [], [], []
    blob_len = 0
    end = next((addr - KSYM_BASE for addr, name in syms if name == "_text_end"), 0)
    if syms and end == 0:
        sys.exit("gen-ksyms: no _text_end symbol (linker.ld)")
    for addr, name in syms:
        if name in ("_text_start", "_text_end") or addr in seen:   # markers; aliases keep the first name
            continue
        seen.add(addr)
        offsets.append(addr - KSYM_BASE)
        name_offs.append(blob_len)
        names.append(name)
        blob_len += len(name) + 1

    def c_array(values):
        rows = [", ".join(f"0x{v:x}" for v in values[i:i + 8]) for i in range(0, len(values), 8)]
        return ",\n    ".join(rows) if rows else "0"

    blob = "".join(n + "\\0" for n in names)
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen-ksyms.py: function symbols for panic backtraces */\n")
        f.write("#include <stdint.h>\n")
        f.write('#define KSYM_SECTION __attribute__((section(".ksyms"), used))\n')
        f.write(f"KSYM_SECTION const uint32_t ksym_count = {len(offsets)};\n")
        f.write(f"KSYM_SECTION const uint32_t ksym_end = 0x{end:x};\n")
        f.write(f"KSYM_SECTION const uint32_t ksym_offsets[] = {{\n    {c_array(offsets)}\n}};\n")
        f.write(f"KSYM_SECTION const uint32_t ksym_name_offsets[] = {{\n    {c_array(name_offs)}\n}};\n")
        # Split the blob into short string pieces to keep lines readable
        pieces = []
        piece = ""
        for n in names:
            piece += n + "\\0"
            if len(piece) > 100:
                pieces.append(piece)
                piece = ""
        if piece or not pieces:
            pieces.append(piece)
        joined = "\n    ".join(f'"{p}"' for p in pieces)
        f.write(f"KSYM_SECTION const char ksym_names[] =\n    {joined};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--nm", default="x86_64-elf-nm")
    ap.add_argument("--out")
    ap.add_argument("--empty", action="store_true", help="write a table with no symbols")
    ap.add_argument("--check", action="store_true", help="compare the function addresses of two ELFs")
    ap.add_argument("elf", nargs="*")
    args = ap.parse_args()

    if args.check:
        if len(args.elf) != 2:
            ap.error("--check needs two ELF files")
        a, b = (text_symbols(args.nm, e) for e in args.elf)
        if a != b:
            diff = next((x, y) for x, y in zip(a + [None], b + [None]) if x != y)
            print(f"gen-ksyms: functions moved between the two kernel links: {diff}", file=sys.stderr)
            return 1
        return 0
    if args.out is None:
        ap.error("--out is required")
    write_table(args.out, [] if args.empty else text_symbols(args.nm, args.elf[0]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
